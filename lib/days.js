// Datas do dia; aceita uma Date (padrão: hoje).
export function daysFor(date = new Date()) {
  const key = `${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
  return (DAYS[key] || '').split(' · ').filter(Boolean);
}
